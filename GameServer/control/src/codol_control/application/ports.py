"""应用端口：业务仅依赖可替换接口，SQLite 与时钟由组合根提供。

UnitOfWork 的全部方法只在 with 范围内使用；实现负责互斥、提交和回滚。
房间、幂等结果与待推送事件必须在同一个工作单元提交。
"""
from __future__ import annotations

from typing import Callable, ContextManager, Protocol
from ..domain.runtime import RuntimeProbeResult


class UnitOfWork(Protocol):
    """一次串行化事务允许访问的持久化操作。"""

    def player(self, key: str) -> dict | None: ...
    def save_player(self, key: str, player: dict) -> None: ...
    def session(self, token_hash: str) -> dict | None: ...
    def save_session(self, token_hash: str, session: dict) -> None: ...
    def revoke_player(self, player_id: str) -> None: ...
    def rooms(self) -> list[dict]: ...
    def save_room(self, room: dict) -> None: ...
    def receipt(self, actor: str, request_id: str) -> dict | None: ...
    def save_receipt(self, actor: str, request_id: str, value: dict) -> None: ...
    def emit(self, room: dict, now: float, type: str = "RoomUpdated") -> int: ...
    def events(self, room_id: str, after: int) -> list[dict]: ...
    def online(self, player_id: str, now: float) -> bool: ...
    def last_seen(self, player_id: str) -> float: ...
    def connected_players(self, now: float) -> int: ...
    # ---- M3 对局：与房间同一事务框架内的读写 ----
    def match(self, match_id: str) -> dict | None: ...
    def active_matches(self) -> list[dict]: ...
    def save_match(self, match: dict) -> None: ...
    def recent_matches(self, limit: int) -> list[dict]: ...


class OnlineRepository(Protocol):
    """提供事务的仓库；业务不依赖实现锁或具体连接。"""

    def transaction(self) -> ContextManager[UnitOfWork]: ...


Clock = Callable[[], float]


class RuntimeProbe(Protocol):
    """运行时预检端口；应用不导入真实或假探测器实现。"""
    def deep_probe(self) -> RuntimeProbeResult: ...
    def port_free(self) -> bool: ...


class BattleSupervisor(Protocol):
    """M3 战斗进程监督端口：进程/套接字/RCON 只存在于 runtime 层实现。

    句柄（handle）是监督器私有的不透明字典：应用层只透传、不解释字段，
    服务重启后句柄失效，恢复路径由监督器的归属核对（pid+可执行路径）承担。
    """
    def launch(self, match_id: str, config: dict) -> dict:
        """按契约启动一局战斗进程；返回监督句柄。失败抛 BattleLaunchError。"""
        ...

    def status(self, handle: dict) -> dict:
        """一次 RCON 状态采样；返回契约 sh1x_status 字段与进程存活事实。"""
        ...

    def stop(self, handle: dict) -> dict:
        """优雅停止（quit→等待→端口释放核对）；返回退出码与清理事实。"""
        ...

    def collect(self, handle: dict, outcome: dict) -> dict:
        """把本局证据写入运行目录 summary.json 并返回脱敏摘要。"""
        ...

    def adopt_or_kill(self, match_id: str, pid: int, run_dir: str) -> dict:
        """服务重启后按 pid+可执行路径核对遗留战斗进程；无法接管则终止。"""
        ...


class AuditStore(Protocol):
    """现有审计写入口，具体数据库类型不进入应用层。"""
    def execute(self, sql: str, params: tuple = ()) -> object: ...


class Settings(Protocol):
    """管理员安装设置端口；实现由组合根选择。"""
    def get(self, key: str) -> object: ...
    def put(self, key: str, value: object) -> None: ...


class Tokens(Protocol):
    """签名与校验端口，不暴露具体编码或密钥实现。"""
    def sign(self, payload: dict, ttl) -> str: ...
    def verify(self, token: str) -> dict: ...


class PasswordTools(Protocol):
    """口令基础设施接口；规则仍由 domain.identity 决定。"""
    def random(self, size: int) -> str: ...
    def salt(self) -> str: ...
    def hash(self, password: str, salt: str) -> str: ...


class Diagnostics(Protocol):
    """脱敏只读证据端口，应用不依赖文件系统布局。"""
    def recent_log_entries(self, limit: int) -> list[dict]: ...
    def list_server_runs(self) -> list[dict]: ...
    def bundle(self) -> dict: ...


class RoomQueries(Protocol):
    """权威房间与连接数查询端口，替代 M1 恒空仓库。"""
    def list_rooms(self) -> dict: ...
    def connected_players(self) -> int: ...
